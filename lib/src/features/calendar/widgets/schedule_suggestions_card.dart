/// Schedule Suggestions Card - AI suggests outfits for free days
class ScheduleSuggestionsCard extends ConsumerStatefulWidget {
  final Map<DateTime, CalendarDay> calendarDays;
  final DateTime selectedDate;

  const ScheduleSuggestionsCard({
    super.key,
    required this.calendarDays,
    required this.selectedDate,
  });

  @override
  ConsumerState<ScheduleSuggestionsCard> createState() => _ScheduleSuggestionsCardState();
}

class _ScheduleSuggestionsCardState extends ConsumerState<ScheduleSuggestionsCard> {
  bool _isLoading = false;

  List<DateTime> _getFreeDays() {
    final freeDays = <DateTime>[];
    final now = DateTime.now();
    
    // Check next 7 days for free slots
    for (int i = 1; i <= 7; i++) {
      final date = now.add(Duration(days: i));
      final dateKey = DateTime(date.year, date.month, date.day);
      
      // Day is free if no outfit is planned
      if (!widget.calendarDays.containsKey(dateKey) || 
          !widget.calendarDays[dateKey]!.hasOutfit) {
        freeDays.add(date);
      }
    }
    
    return freeDays.take(3).toList(); // Show max 3 suggestions
  }

  Future<void> _requestOutfitSuggestion(DateTime date) async {
    setState(() => _isLoading = true);
    HapticFeedback.mediumImpact();
    
    try {
      // TODO: Call AI service to generate outfit suggestion
      await Future.delayed(const Duration(seconds: 1));
      
      if (mounted) {
        // Show save to calendar dialog with suggested outfit
        showDialog(
          context: context,
          builder: (context) => SaveOutfitToCalendarDialog(
            outfitName: 'AI Suggested Outfit',
            outfitImageUrl: null, // Will be generated by AI
          ),
        );
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Failed to generate suggestion: ${e.toString()}'),
            backgroundColor: context.appTheme.accentError,
          ),
        );
      }
    } finally {
      if (mounted) {
        setState(() => _isLoading = false);
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    final theme = context.appTheme;
    final freeDays = _getFreeDays();
    
    if (freeDays.isEmpty) {
      return SizedBox.shrink();
    }

    return Container(
      margin: EdgeInsets.all(16),
      padding: EdgeInsets.all(20),
      decoration: BoxDecoration(
        color: theme.surface,
        borderRadius: BorderRadius.circular(16),
        border: Border.all(
          color: theme.primary.withOpacity(0.2),
          width: 1,
        ),
        boxShadow: [
          BoxShadow(
            color: theme.primary.withOpacity(0.1),
            blurRadius: 10,
            offset: const Offset(0, 4),
          ),
        ],
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            children: [
              Container(
                padding: EdgeInsets.all(8),
                decoration: BoxDecoration(
                  color: theme.primary.withOpacity(0.1),
                  borderRadius: BorderRadius.circular(8),
                ),
                child: Icon(
                  Icons.auto_awesome,
                  color: theme.primary,
                  size: 20,
                ),
              ),
              SizedBox(width: 12),
              Expanded(
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text(
                      'Schedule Suggestions',
                      style: theme.bodyMedium(color: theme.textPrimary).copyWith(
                        fontWeight: FontWeight.w600,
                      ),
                    ),
                    SizedBox(height: 2),
                    Text(
                      'AI can suggest outfits for free days',
                      style: theme.bodySmall(color: theme.textSecondary),
                    ),
                  ],
                ),
              ),
            ],
          ),
          
          SizedBox(height: 16),
          
          ...freeDays.map((date) => _buildSuggestionItem(theme, date)),
        ],
      ),
    );
  }

  Widget _buildSuggestionItem(AppThemeData theme, DateTime date) {
    final dateStr = DateFormat('EEEE, MMM d').format(date);
    final isToday = date.year == DateTime.now().year &&
        date.month == DateTime.now().month &&
        date.day == DateTime.now().day;
    
    return Container(
      margin: EdgeInsets.only(bottom: 12),
      padding: EdgeInsets.all(12),
      decoration: BoxDecoration(
        color: theme.surfaceElevated,
        borderRadius: BorderRadius.circular(12),
        border: Border.all(
          color: theme.borderLight.withOpacity(0.3),
          width: 1,
        ),
      ),
      child: Row(
        children: [
          Container(
            width: 40,
            height: 40,
            decoration: BoxDecoration(
              color: theme.primary.withOpacity(0.1),
              borderRadius: BorderRadius.circular(8),
            ),
            child: Center(
              child: Text(
                '${date.day}',
                style: theme.bodyMedium(color: theme.primary).copyWith(
                  fontWeight: FontWeight.w600,
                ),
              ),
            ),
          ),
          SizedBox(width: 12),
          Expanded(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(
                  isToday ? 'Today' : dateStr,
                  style: theme.bodyMedium(color: theme.textPrimary).copyWith(
                    fontWeight: FontWeight.w500,
                  ),
                ),
                SizedBox(height: 2),
                Text(
                  'No outfit planned',
                  style: theme.bodySmall(color: theme.textSecondary),
                ),
              ],
            ),
          ),
          TextButton.icon(
            onPressed: _isLoading ? null : () => _requestOutfitSuggestion(date),
            icon: _isLoading
                ? SizedBox(
                    width: 16,
                    height: 16,
                    child: CircularProgressIndicator(
                      strokeWidth: 2,
                      color: theme.primary,
                    ),
                  )
                : Icon(Icons.auto_awesome, size: 16, color: theme.primary),
            label: Text(
              'Suggest',
              style: theme.bodySmall(color: theme.primary).copyWith(
                fontWeight: FontWeight.w600,
              ),
            ),
            style: TextButton.styleFrom(
              padding: EdgeInsets.symmetric(horizontal: 12, vertical: 8),
            ),
          ),
        ],
      ),
    );
  }
}
